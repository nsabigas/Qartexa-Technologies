#!/usr/bin/env python3
"""Builds js/qx-inventory.js: every page (with its hero element) and every replaceable image slot.
Run again whenever pages are added:  python3 tools/build-inventory.py"""
import re,glob,os,json,html
ROOT=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
def group(f):
    if f=='index.html': return 'Home'
    if f.startswith('solutions/'): return 'Solutions'
    if f.startswith('industries/'): return 'Industries'
    if f in('careers.html','job.html','resources.html','blog.html','post.html','tenders.html','tender.html'): return 'Careers & resources'
    if f in('contact.html','form.html'): return 'Contact'
    if f in('privacy.html','terms.html','cookies.html','accessibility.html','legal.html'): return 'Legal'
    return 'Company & other'
pages=[];images=[];seen=set()
for p in sorted(glob.glob(ROOT+'/**/*.html',recursive=True)):
    f=os.path.relpath(p,ROOT).replace(os.sep,'/')
    if f in('admin.html','portal.html'): continue
    s=open(p,encoding='utf-8').read()
    key=(re.search(r'<html[^>]*data-cms-page="([^"]+)"',s) or re.search(r'data-cms-page="([^"]+)"',s))
    if not key: continue
    key=key.group(1)
    hero='hero' if re.search(r'<section[^>]*class="[^"]*\bhero\b',s) else ('subhero' if re.search(r'<(section|header)[^>]*class="[^"]*\bsubhero\b',s) else 'none')
    clean=lambda x:html.unescape(re.sub(r'\s+',' ',re.sub(r'<[^>]+>','',x))).strip()
    h1=re.search(r'<h1[^>]*>(.*?)</h1>',s,re.S); h1=clean(h1.group(1)) if h1 else ''
    cr=re.search(r'class="[^"]*(?:crumb|breadcrumb)[^"]*"[^>]*>(.*?)</(?:nav|div|p|ol)>',s,re.S); cr=clean(re.sub(r'<[^>]+>','/',cr.group(1))).split('/')[-1].strip() if cr else ''
    title=h1 if (h1 and len(h1)<=42) else (cr or h1 or key)
    title={'index.html':'Home','job.html':'Job page (each vacancy)','post.html':'Article page (each blog post)','solution.html':'Solution page (database-driven)','tender.html':'Tender page (each tender)','form.html':'Form page (any form)','about.html':'About Qartexa','approach.html':'Our approach','blog.html':'Blog & insights','careers.html':'Careers','contact.html':'Contact','cookies.html':'Cookie preferences','ecosystem.html':'Ecosystem & partners','tenders.html':'Tenders & procurement','solutions/index.html':'Solutions overview','industries/index.html':'Industries overview'}.get(f,title)
    hs=re.search(r'<(section|header)[^>]*class="[^"]*\b(hero|subhero)\b[^"]*"[^>]*>.*?</\1>',s,re.S)
    slot=None
    if hs:
        m2=re.search(r'<[a-z]+\b[^>]*?data-cms-(img|bg)="([^"]+)"[^>]*>',hs.group(0))
        if m2 and m2.group(1)=='img':   # a data-cms-bg element is a decorative background layer, not a photo
            tag=m2.group(0); src=re.search(r'\ssrc="([^"]+)"',tag); alt=re.search(r'\salt="([^"]*)"',tag)
            slot={'id':m2.group(2),'kind':m2.group(1),'src':src.group(1) if src else '','alt':html.unescape(alt.group(1)) if alt else ''}
    title=re.sub(r'\s*\|.*$','',title).rstrip('.')
    pages.append({'key':key,'file':f,'title':title,'hero':hero,'group':group(f),'slot':slot})
    for m in re.finditer(r'<(img|[a-z]+)\b[^>]*?data-cms-(img|bg)="([^"]+)"[^>]*>',s):
        tag=m.group(0); sid=m.group(3)
        if sid in seen: continue
        seen.add(sid)
        src=re.search(r'\ssrc="([^"]+)"',tag); alt=re.search(r'\salt="([^"]*)"',tag)
        images.append({'id':sid,'page':key,'file':f,'kind':m.group(2),'src':(src.group(1) if src else ''),'alt':html.unescape(alt.group(1)) if alt else ''})
cards=[{'key':'card:solutions:%d'%i,'page':'index','label':l,'src':'img/%s-hero-card.jpg'%n} for i,(l,n) in enumerate([('Digital transformation card','digital-transformation'),('Cybersecurity card','cybersecurity'),('Software engineering card','software-engineering'),('ICT consultancy card','ict-consultancy')],1)]
out='/* Generated by tools/build-inventory.py. Do not edit by hand. */\nwindow.QX_INVENTORY='+json.dumps({'pages':pages,'images':images,'cards':cards},ensure_ascii=False,separators=(',',':'))+';\n'
open(ROOT+'/js/qx-inventory.js','w',encoding='utf-8').write(out)
from collections import Counter
print('pages',len(pages),Counter(x['hero'] for x in pages),'| replaceable <img>/bg slots',len(images))
print([ (x['key'],x['file']) for x in pages if x['file'].startswith('solutions/index') ])
print('pages whose hero already contains a replaceable photo:',sum(1 for x in pages if x['slot']),'| without a photo:',[x['file'] for x in pages if not x['slot']])
print('pages without any hero element:',[x['file'] for x in pages if x['hero']=='none'])
